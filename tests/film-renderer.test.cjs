"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const source = fs.readFileSync(path.join(__dirname, "..", "film-renderer.js"), "utf8");
function load(extra = {}) {
  const context = vm.createContext(extra);
  vm.runInContext(`${source}\nglobalThis.renderer = FilmExposureMath;`, context);
  return context.renderer;
}
const film = load();
const rgba = (rgb, alpha = 255) => Uint8ClampedArray.from(rgb.flatMap((value, index) => index % 3 === 2 ? [value, alpha] : [value]));
function render(first, second, settings = {}) {
  const output = new Uint8ClampedArray(first.length);
  film.createMixer(settings)(first, second, output);
  return Array.from(output);
}
function renderThreshold(first, second, settings = {}) {
  const output = new Uint8ClampedArray(first.length);
  film.createThresholdMixer(settings)(first, second, output);
  return Array.from(output);
}

test("the experimental module loads in a plain browser scope without Node or DOM globals", () => {
  assert.equal(film.version, "assumed-film-v1");
  assert.ok(Object.isFrozen(film));
  assert.ok(Object.isFrozen(film.parameters));
  assert.equal(film.parameters.toe, -7);
  assert.equal(film.parameters.shoulder, 4);
});


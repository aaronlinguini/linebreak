test("bright neutral regions suppress coloured detail while dark regions retain primary saturation", () => {
  for (const base of [200,255]) {
    for (const addedColour of [[255,0,0], [0,255,0], [0,0,255]]) {
      const output = renderNegative(rgba([base,base,base]), rgba(addedColour), { monochrome: false });
      const channels = output.slice(0,3);
      assert.ok(Math.max(...channels) - Math.min(...channels) <= 4, "a bright light-table region must remain nearly neutral when coloured detail is added");
    }
  }
  for (let channel = 0; channel < 3; channel++) {
    const primary = [0,0,0];
    primary[channel] = 255;
    const output = renderNegative(rgba(primary), rgba([0,0,0]), { monochrome: false });
    assert.ok(output[channel] >= 230);
    assert.ok(output.slice(0,3).every((value, index) => index === channel || value === 0), "a primary in a dark region must not be bleached toward gray");
  }
  const sourceRamp = rgba(Array.from({ length: 256 }, (_, value) => [value,100,40]).flat());
  const secondRamp = rgba(Array.from({ length: 256 }, () => [30,80,150]).flat());
  const pixels = renderNegative(sourceRamp, secondRamp, { monochrome: false });
  for (let i = 4; i < pixels.length; i += 4) {
    for (let channel = 0; channel < 3; channel++) {
      assert.ok(Math.abs(pixels[i + channel] - pixels[i - 4 + channel]) <= 5, "colour ramps must cross the former 185 threshold continuously");
    }
  }
});


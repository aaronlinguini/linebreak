test("negative printing suppresses portrait contrast over bone while retaining it in a dark cavity", () => {
  const portrait = rgba([30,30,30,80,80,80,128,128,128,200,200,200]);
  const dark = rgba([35,35,35,35,35,35,35,35,35,35,35,35]);
  const bone = rgba([160,160,160,160,160,160,160,160,160,160,160,160]);
  const darkValues = renderNegative(dark, portrait).filter((_, i) => i % 4 === 0);
  const boneValues = renderNegative(bone, portrait).filter((_, i) => i % 4 === 0);
  const oldBoneValues = renderSmooth(bone, portrait).filter((_, i) => i % 4 === 0);
  const span = (values) => Math.max(...values) - Math.min(...values);
  assert.ok(span(darkValues) > 100, "facial tonal separation should remain available in a dark cavity");
  assert.ok(span(boneValues) < 20, "the print toe should flatten detail over moderately bright bone");
  assert.ok(span(boneValues) < span(oldBoneValues) / 2, "the new response must address the measured midtone-retention mismatch");
  assert.ok(boneValues.at(-1) < 255, "loss of portrait detail must not require pure white output");
});


test("chunked mixing writes only the selected pixels and matches a full render", () => {
  const settings = { baseExposure: -1, participantExposure: -0.5, monochrome: false };
  const mix = film.createMixer(settings);
  const output = new Uint8ClampedArray(first.length).fill(77);
  mix(first, second, output, 4, 16);
  assert.deepEqual(Array.from(output.slice(0, 4)), [77,77,77,77]);
  assert.ok(output.slice(16).every((byte) => byte === 77));
  mix(first, second, output, 0, 4);
  mix(first, second, output, 16, first.length);
  assert.deepEqual(Array.from(output), render(first, second, settings));
});

test("invalid settings and invalid pixel chunks fail before processing", () => {
  for (const invalid of [NaN, Infinity, -3.1, 2.1, "0"]) {
    assert.throws(() => film.createMixer({ baseExposure: invalid }), /exposure must be between/);
    assert.throws(() => film.createMixer({ participantExposure: invalid }), /exposure must be between/);
  }
  for (const invalid of [NaN, Infinity, 0, 0.64, 1.51, "1"]) {
    assert.throws(() => film.createMixer({ filmContrast: invalid }), /Film contrast must be between/);
  }
  assert.throws(() => film.createMixer({ monochrome: "false" }), /Monochrome must be/);
  const mix = film.createMixer();
  assert.throws(() => mix([0,0,0], [0,0,0], [0,0,0]), /RGBA dimensions/);
  assert.throws(() => mix(first, second, new Uint8ClampedArray(4)), /RGBA dimensions/);
  for (const [start, end] of [[1, 4], [0, 5], [-4, 4], [8, 4], [0, first.length + 4], [NaN, 4]]) {
    assert.throws(() => mix(first, second, new Uint8ClampedArray(first.length), start, end), /aligned RGBA boundaries/);
  }
});


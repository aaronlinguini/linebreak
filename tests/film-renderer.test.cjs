const source = fs.readFileSync(path.join(__dirname, "..", "film-renderer.js"), "utf8");
function load(extra = {}) {
  const context = vm.createContext(extra);
  vm.runInContext(`${source}\nglobalThis.renderer = FilmExposureMath;`, context);
  return context.renderer;
}
const film = load();
const rgba = (rgb, alpha = 255) => Uint8ClampedArray.from(rgb.flatMap((value, index) => index % 3 === 2 ? [value, alpha] : [value]));
function render(first, second, settings = {}) {
  const output = new Uint8ClampedArray(first.length);
  film.createMixer(settings)(first, second, output);
  return Array.from(output);
}
function renderSmooth(first, second, settings = {}) {
  const output = new Uint8ClampedArray(first.length);
  film.createSmoothMixer(settings)(first, second, output);
  return Array.from(output);
}
function renderNegative(first, second, settings = {}) {
  const output = new Uint8ClampedArray(first.length);
  film.createNegativeMixer(settings)(first, second, output);
  return Array.from(output);
}


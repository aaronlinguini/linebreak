test("black contributes no exposure at 0 EV for every grayscale byte", () => {
  const ramp = rgba(Array.from({ length: 256 }, (_, byte) => [byte, byte, byte]).flat());
  const black = new Uint8ClampedArray(ramp.length);
  for (const monochrome of [true, false]) {
    assert.deepEqual(render(ramp, black, { baseExposure: 0, participantExposure: 0, monochrome }), Array.from(ramp));
  }
});

